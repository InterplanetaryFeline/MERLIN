"""Turn outputs/validation/validation_results.json into the validation workbook, figures and markdown tables."""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter
OUT = os.path.join(ROOT, "outputs", "validation")
D = json.load(open(os.path.join(OUT, "validation_results.json"), encoding="utf-8"))
V, C = D["vehicles"], D["combos"]
HDR = PatternFill("solid", fgColor="1F3864"); thin = Side(style="thin", color="BFBFBF"); B = Border(left=thin, right=thin, top=thin, bottom=thin)
CALC = PatternFill("solid", fgColor="F2F2F2")
VARIANTS = [("base", "As-published split"), ("opt", "Optimised split"), ("lean", "Lean margins (diagnostic)"),
            ("calibrated", "Published casing k (diagnostic)")]


def gv(d, variant, field, stage=None):
    """Value of a metric for a variant, or None when that variant was not feasible."""
    m = d.get(variant)
    if not m:
        return None
    return m[field].get(str(stage)) if stage is not None else m[field]


def hdr(ws, r, heads):
    for j, h in enumerate(heads, 1):
        c = ws.cell(row=r, column=j, value=h); c.font = Font(name="Arial", bold=True, color="FFFFFF", size=10); c.fill = HDR
        c.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center"); c.border = B


wb = Workbook()
ws = wb.active; ws.title = "README"
for i, t in enumerate([
    "Validation of the sizing engine against real launch vehicles and a propellant-type comparison. Generated by tools/run_validation.py + tools/build_validation_report.py.",
    "Reference values come from the public sources listed per row (Wikipedia, operator websites, NASA, and the book's own Tables 4.8/5.1/5.2). Rows marked LOW confidence come from a community wiki.",
    "Variants: 'As-published split' = the dv split written in the case file; 'Optimised' = GLOM-minimising split from optimize_dv_split(); "
    "'Lean margins' = optimised split with no mass-growth margin, no loading margin and residual 1 % (liquids) / 0 % (solids); "
    "'Published casing k' = solid stages sized with each motor's REAL inert/propellant ratio instead of the book's SRM casing MER.",
    "The last two are DIAGNOSTICS that separate 'the model is wrong' from 'the statistical mass relations are conservative'. Nothing was tuned to match a vehicle.",
    "Engine and motor values that were not found in the sources are tagged 'assumed' inside each validation/*.yaml; every leaf carries its source.",
    "Grey cells are live Excel formulas (predicted / published).",
    "Model limitations affecting the comparison: no trajectory simulation (ascent losses come from the book regression, RMS error ~260 m/s); constant thrust and Isp per stage "
    "(a front-loaded solid motor is modelled at its burn-average thrust); no propellant crossfeed; no recovery hardware; a wing (Pegasus) is not modelled."]):
    ws.cell(row=2 + i, column=1, value=t).alignment = Alignment(wrap_text=True)
ws.column_dimensions["A"].width = 160

ws = wb.create_sheet("Real_Vehicles")
heads = ["Vehicle", "Quantity", "Published value", "Published source"] + [v[1] for v in VARIANTS] \
    + ["Ratio as-published", "Ratio optimised", "Ratio lean", "Ratio calibrated"]
hdr(ws, 1, heads)
r = 2
rows_for_plot = []
for key, d in V.items():
    ref = d["ref"]

    def add(q, pub, src, vals):
        global r
        ws.cell(row=r, column=1, value=ref["title"]); ws.cell(row=r, column=2, value=q)
        ws.cell(row=r, column=3, value=pub); ws.cell(row=r, column=4, value=src)
        for j, v in enumerate(vals, 5):
            ws.cell(row=r, column=j, value=v)
        if pub:
            for j, col in ((9, "E"), (10, "F"), (11, "G"), (12, "H")):
                c = ws.cell(row=r, column=j, value=f"=IF({col}{r}=\"\",\"\",{col}{r}/C{r})")
                c.number_format = "0.000"; c.fill = CALC
        for j in (3, 5, 6, 7, 8):
            ws.cell(row=r, column=j).number_format = "#,##0.0"
        for j in range(1, 13):
            ws.cell(row=r, column=j).border = B
        r += 1

    add("Gross liftoff mass [kg]", ref["glom"][0], ref["glom"][1], [gv(d, v, "glom") for v, _ in VARIANTS])
    rows_for_plot.append((key, ref["title"], ref["glom"][0], gv(d, "base", "glom"), gv(d, "opt", "glom"),
                          gv(d, "lean", "glom"), gv(d, "calibrated", "glom")))
    add("Overall length [m]", ref["length"][0], ref["length"][1], [gv(d, v, "length") for v, _ in VARIANTS])
    for k, (v, s) in ref["prop"].items():
        add(f"Stage {k} loaded propellant [kg]", v, s, [gv(d, vr, "prop", k) for vr, _ in VARIANTS])
    for k, (v, s) in ref["dry"].items():
        add(f"Stage {k} inert mass at burnout [kg] (dry + residual + margin)", v, s, [gv(d, vr, "dry", k) for vr, _ in VARIANTS])
    if ref.get("boosters"):
        n, mp, mi, src = ref["boosters"]
        add(f"Strap-on booster propellant each [kg] ({n} boosters)", mp, src, [mp] * 4)
        add("Strap-on booster inert mass each [kg]", mi, src, [mi] * 4)
    add("Required dv from the loss model [m/s]", None, "n/a", [gv(d, v, "dv") for v, _ in VARIANTS])
for j, w in enumerate([44, 54, 16, 60, 16, 16, 18, 20, 13, 13, 13, 13], 1):
    ws.column_dimensions[get_column_letter(j)].width = w
ws.freeze_panes = "C2"; ws.auto_filter.ref = f"A1:L{r - 1}"

ws = wb.create_sheet("DeltaV_From_Published_Masses")
hdr(ws, 1, ["Vehicle", "Ideal dv from published stage masses [m/s]", "Required dv (loss model, sized design) [m/s]",
            "Capability margin [%] (Excel)", "Source of masses"])
for i, (key, d) in enumerate([(k, v) for k, v in V.items() if v["cap"]], 2):
    ws.cell(row=i, column=1, value=d["ref"]["title"]); ws.cell(row=i, column=2, value=d["cap"]["dv_published_masses"]).number_format = "#,##0"
    ws.cell(row=i, column=3, value=d["cap"]["dv_required"]).number_format = "#,##0"
    c = ws.cell(row=i, column=4, value=f"=100*(B{i}/C{i}-1)"); c.number_format = "+0.0;-0.0"; c.fill = CALC
    ws.cell(row=i, column=5, value=d["cap"]["source"])
for j, w in enumerate([46, 30, 34, 22, 80], 1):
    ws.column_dimensions[get_column_letter(j)].width = w

ws = wb.create_sheet("Structural_Factors")
hdr(ws, 1, ["Vehicle", "Stage", "Type", "s predicted (optimised run)", "s from published masses", "Ratio (Excel)", "Published source"])
r = 2
for key, d in V.items():
    for k, (v, s) in d["ref"]["dry"].items():
        p = d["ref"]["prop"].get(k)
        if not p:
            continue
        s_pub = v / (v + p[0])
        s_pred = gv(d, "opt", "s", k)
        ws.cell(row=r, column=1, value=d["ref"]["title"]); ws.cell(row=r, column=2, value=int(k))
        ws.cell(row=r, column=3, value="solid" if d.get("solid", [])[int(k) - 1:int(k)] == [True] else "liquid")
        ws.cell(row=r, column=4, value=s_pred).number_format = "0.0000"
        ws.cell(row=r, column=5, value=s_pub).number_format = "0.0000"
        c = ws.cell(row=r, column=6, value=f"=D{r}/E{r}"); c.number_format = "0.00"; c.fill = CALC
        ws.cell(row=r, column=7, value=s)
        r += 1
for j, w in enumerate([44, 8, 10, 22, 22, 12, 60], 1):
    ws.column_dimensions[get_column_letter(j)].width = w

ws = wb.create_sheet("Propellant_Types")
hdr(ws, 1, ["Combination (same 10 t / 400 km LEO mission, book loss regression, GLOM-minimising split)", "GLOM [kg]", "Total propellant [kg]", "Total dry mass [kg]", "Payload fraction [-]", "Overall length [m]", "dv required [m/s]", "Stage 1 dv share", "Stage 1 s", "Stage 2 s", "Feasible & converged"])
names = {"kerolox": "LOX/RP-1 + LOX/RP-1", "methalox": "LOX/LCH4 + LOX/LCH4", "hydrolox": "LOX/LH2 + LOX/LH2", "kerolox_hydrolox": "LOX/RP-1 + LOX/LH2", "hypergolic": "N2O4/A-50 + N2O4/A-50"}
for i, (k, m) in enumerate(C.items(), 2):
    vals = [names[k], m["glom"], m["prop_total"], m["dry_total"], None, m["length"], m["dv"], m["fractions"][0], m["s"]["1"], m["s"]["2"], "yes" if m["ok"] else "NO: " + "; ".join(m["errors"])]
    for j, v in enumerate(vals, 1):
        ws.cell(row=i, column=j, value=v)
    c = ws.cell(row=i, column=5, value=f"=10000/B{i}"); c.fill = CALC
    for j, f in ((2, "#,##0"), (3, "#,##0"), (4, "#,##0"), (5, "0.0000"), (6, "0.0"), (7, "#,##0"), (8, "0.000"), (9, "0.0000"), (10, "0.0000")):
        ws.cell(row=i, column=j).number_format = f
ws.cell(row=8, column=1, value="Isp values: kerolox = Falcon 9 Merlin 313/285 s & MVac 348 s (orbitcodex); hypergolic = Titan II LR-87 296/258 & LR91 316 s (Wikipedia); upper-stage LH2 = RL10B-2 465.5 s (orbitcodex); first-stage LH2 410/360 s and all methalox values are ASSUMED/illustrative.")
for j, w in enumerate([70, 14, 18, 18, 16, 16, 16, 14, 12, 12, 40], 1):
    ws.column_dimensions[get_column_letter(j)].width = w
wb.save(os.path.join(OUT, "validation_report.xlsx"))

# ----------------------------------------------------------------------------------- figures
fig, (a1, a2) = plt.subplots(1, 2, figsize=(16, 6), gridspec_kw=dict(width_ratios=[1.7, 1]))
x = np.arange(len(rows_for_plot)); w = 0.2
for k, (lab, col) in enumerate((("As-published split", "#4472C4"), ("Optimised split", "#ED7D31"),
                                ("Lean margins (diag.)", "#70AD47"), ("Published casing k (diag.)", "#7030A0"))):
    vals = [(row[3 + k] / row[2]) if row[3 + k] else np.nan for row in rows_for_plot]
    a1.bar(x + (k - 1.5) * w, vals, w, label=lab, color=col)
a1.axhline(1.0, color="k", lw=1)
a1.set_xticks(x); a1.set_xticklabels([r[1].split("(")[0].strip() for r in rows_for_plot], rotation=20, fontsize=7.5, ha="right")
a1.set_ylabel("predicted GLOM / published GLOM")
a1.set_title("Sizing engine vs real vehicles (payload and orbit as published)")
a1.legend(fontsize=8); a1.grid(axis="y", alpha=.3)
names_l = [names[k] for k in C]
glom = [C[k]["glom"] / 1e3 for k in C]; dry = [C[k]["dry_total"] / 1e3 for k in C]
a2.bar(names_l, glom, color="#4472C4", label="GLOM [t]")
a2.bar(names_l, dry, color="#C00000", label="total dry mass [t]")
for i, k in enumerate(C):
    a2.text(i, glom[i] + 4, f"{glom[i]:.0f} t\n({C[k]['payload_fraction']*100:.1f}% payload)", ha="center", fontsize=8)
a2.set_title("Same mission (10 t, 400 km LEO): propellant types"); a2.set_ylabel("tonnes"); a2.legend()
plt.setp(a2.get_xticklabels(), rotation=20, fontsize=8, ha="right"); a2.grid(axis="y", alpha=.3)
plt.tight_layout(); plt.savefig(os.path.join(OUT, "validation_comparison.png"), dpi=150)

# ----------------------------------------------------------------------------------- markdown
def pct(v, ref, applies=True):
    if not applies:
        return "n/a"
    return f"{v/1e3:,.1f} ({v/ref-1:+.0%})" if v else "not feasible"


L = ["# Validation data tables", "",
     "Generated from `outputs/validation/validation_results.json`. **No parameter was tuned to match a vehicle.** "
     "Unsourced engine values are tagged `assumed` in `validation/*.yaml`.", "",
     "## 1. Real vehicles (payload and orbit as published)", "",
     "| Vehicle | Published GLOM [t] | As-published split | Optimised split | Lean margins (diag.) | Published casing k (diag.) | Length pred./pub. [m] |",
     "|---|---|---|---|---|---|---|"]
for key, d in V.items():
    g = d["ref"]["glom"][0]
    L.append(f"| {d['ref']['title']} | {g/1e3:,.1f} | {pct(gv(d,'base','glom'), g)} | {pct(gv(d,'opt','glom'), g)} | "
             f"{pct(gv(d,'lean','glom'), g)} | {pct(gv(d,'calibrated','glom'), g, bool(d.get('calibrated_k')))} | "
             f"{gv(d,'opt','length'):.1f} / {d['ref']['length'][0]:.1f} |")
L += ["", "## 2. Delta-v of the *published* stage masses vs the requirement the tool computes", "",
      "| Vehicle | Ideal dv from published masses [m/s] | Required (loss model) [m/s] | Margin |", "|---|---|---|---|"]
for key, d in V.items():
    if d["cap"]:
        L.append(f"| {d['ref']['title']} | {d['cap']['dv_published_masses']:,.0f} | {d['cap']['dv_required']:,.0f} | "
                 f"{100*(d['cap']['dv_published_masses']/d['cap']['dv_required']-1):+.1f} % |")
L += ["", "## 3. Structural factors: predicted vs published", "",
      "| Vehicle | Stage | Type | s predicted | s published | ratio |", "|---|---|---|---|---|---|"]
for key, d in V.items():
    for k, (v, s) in d["ref"]["dry"].items():
        p = d["ref"]["prop"].get(k)
        if not p:
            continue
        s_pub, s_pred = v / (v + p[0]), gv(d, "opt", "s", k)
        tp = "solid" if d.get("solid", [])[int(k) - 1:int(k)] == [True] else "liquid"
        L.append(f"| {d['ref']['title'].split('(')[0].strip()} | {k} | {tp} | {s_pred:.4f} | {s_pub:.4f} | {s_pred/s_pub:.2f} |")
L += ["", "## 4. Propellant types on one mission (10 t to 400 km LEO, 28.5 deg, GLOM-minimising dv split)", "",
      "| Combination | GLOM [t] | Dry [t] | Payload fraction | Length [m] | dv [m/s] |", "|---|---|---|---|---|---|"]
for k, m in C.items():
    L.append(f"| {names[k]} | {m['glom']/1e3:,.1f} | {m['dry_total']/1e3:,.1f} | {m['payload_fraction']*100:.2f} % | {m['length']:.1f} | {m['dv']:,.0f} |")
open(os.path.join(ROOT, "docs", "VALIDATION_REPORT_DATA.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L))
print("\n".join(L))
