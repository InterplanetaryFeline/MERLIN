def get(d, path):
    for k in path.split("."):
        d = d[int(k)] if isinstance(d, list) else d[k]
    return d


def S(d, path, v, s, t="reference", u=None, desc=None):
    keys = path.split(".")
    cur = d
    for k in keys[:-1]:
        cur = cur[int(k)] if isinstance(cur, list) else cur[k]
    last = keys[-1]
    old = cur.get(last) if isinstance(cur, dict) else None
    cur[last] = dict(v=v, u=(old or {}).get("u", u or "-"), d=(old or {}).get("d", desc or last), s=s, t=t)


TW = {   # published/derived thrust-to-weight ratios used in "rubber-engine" mode (thrust scales with vehicle mass)
    "electron": [(1.49, "Derived: lift-off 190 kN / (13,000 kg x g0), rocketlabusa.com"), (0.9, "Derived: 25.8 kN / ~2.9 t stage-2+payload mass (community-wiki masses, low confidence)")],
    "falcon9": [(1.413, "Derived: 7,607 kN SL thrust / (549,054 kg x g0), NASA/orbitalradar"), (0.74, "Derived: 981 kN / ~136 t stage-2 stack (107.5 t propellant est.)")],
    "titan2": [(1.258, "Derived: 1,900 kN / (154,000 kg x g0), Wikipedia Titan II"), (1.28, "Derived: 445 kN / ~35 t stage-2 stack")],
    "zhuque2": [(1.224, "Derived: 2,628 kN / (219,000 kg x g0), everydayastronaut"), (1.8, "ASSUMED: 784 kN / ~44 t stage-2 stack (masses not published)")],
    "saturn5": [(1.183, "Book Example 3.8 (p.176): T/W0 = 1.183"), (0.75, "Derived: 5,141 kN / ~700 t stack"), (0.60, "Derived: 1,033 kN / ~175 t stack")],
}


def write(name, raw, meta):
    if name in TW:
        for i, (tw, src) in enumerate(TW[name]):
            S(raw["stages"][i], "engine.thrust_vac_per_engine_N", None, "rubber-engine mode: thrust follows T/W", "user")
            S(raw["stages"][i], "engine.thrust_to_weight_ignition", tw, src, "reference" if "ASSUMED" not in src else "assumed")
    raw = copy.deepcopy(raw)
    raw["meta"] = meta
    with open(os.path.join(OUT, name + ".yaml"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# AUTO-GENERATED by tools/make_validation_cases.py - real-vehicle validation case. Sources are in each leaf's 's' field.\n")
        yaml.safe_dump(raw, f, sort_keys=False, width=220)


def stage_common(st, name, D, n, F_vac=None, tw=None, isp_vac=None, isp_sl=None, mode="weighted", eps=None, pc=None, L=None, de=None, emb=0.5, src="", t="reference"):
    S(st, "name", name, "label", "user")
    S(st, "diameter_m", D, src)
    e = st["engine"]
    S(e, "n_engines", n, src)
    S(e, "thrust_vac_per_engine_N", F_vac, src, t if F_vac else "user")
    S(e, "thrust_to_weight_ignition", tw, src, t if tw else "user")
    S(e, "isp_vac_s", isp_vac, src, t)
    S(e, "isp_sl_s", isp_sl, src, t if isp_sl else "assumed")
    S(e, "isp_effective_mode", mode, "Book Eq. 4:18 weighting for atmospheric stage / vacuum Isp for upper stage (explicit modelling assumption)", "assumed")
    if eps is not None: S(e, "expansion_ratio", eps[0], eps[1], eps[2])
    if pc is not None: S(e, "chamber_pressure_Pa", pc[0], pc[1], pc[2])
    S(e, "length_m", L, "Assumed engine envelope (not found in sources)", "assumed")
    S(e, "exit_diameter_m", de, "Assumed nozzle exit diameter (not found in sources)", "assumed")
    S(e, "embed_fraction", emb, "Assumed", "assumed")


