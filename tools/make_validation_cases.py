def add_stage(r, n):
    """Make the stage list n entries long by copying the last stage template."""
    while len(r["stages"]) < n:
        r["stages"].append(copy.deepcopy(r["stages"][-1]))
    r["stages"] = r["stages"][:n]
    return r["stages"]


